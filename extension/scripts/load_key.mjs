// Copies GROQ_API_KEY from the project's .env into src/local_key.js, so the
// unpacked extension can sort with the model without the key being typed in.
// src/local_key.js is git-ignored: the key never reaches the repository.
// Run again after changing the key, then reload the extension.
//
//   node extension/scripts/load_key.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const envPath = fileURLToPath(new URL("../../.env", import.meta.url));
const outPath = fileURLToPath(new URL("../src/local_key.js", import.meta.url));

let key = "";
try {
  for (const line of readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const match = /^\s*GROQ_API_KEY\s*=\s*(.*)$/.exec(line);
    if (match) key = match[1].trim().replace(/^["']|["']$/g, "");
  }
} catch {
  console.error("No .env found next to the backend; nothing written.");
  process.exit(1);
}
if (!key) {
  console.error("GROQ_API_KEY is missing from .env; nothing written.");
  process.exit(1);
}

writeFileSync(outPath,
  "// Generated by scripts/load_key.mjs from .env. Git-ignored; do not commit or share.\n" +
  "globalThis.InboxIQ_LOCAL_KEY = " + JSON.stringify(key) + ";\n");
console.log("Wrote extension/src/local_key.js. Reload the extension in chrome://extensions.");
